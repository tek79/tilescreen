"""Writes src/app/tilescreen/core/MicroTables.java from the tables the C microfrontend builds.

The C (TensorFlow Lite Micro's microfrontend with kissfft v130, as pymicro_features and ESPHome build it) works its
window, twiddles, filterbank weights and PCAN gain table out with float maths (cosf, log1pf, powf). Java's maths can land
one step away on a few of them, so the app carries the C's numbers instead of working them out.

    python3 test/wake_tables.py <dump>     where <dump> is the output of the small C program in test/wake_test.py
"""
import sys

ORDER = ["window", "super", "twiddles", "bank", "weights", "unweights", "lut"]


# Java reads \\u escapes before anything else, so a line break, a quote or a backslash must be written the other way.
SPECIAL = {0x0A: "\\012", 0x0D: "\\015", 0x22: "\\042", 0x5C: "\\134"}


def char(v):
    return SPECIAL.get(v, "\\u%04x" % v)


def main(dump):
    rows = {}
    for line in open(dump):
        parts = line.split()
        if parts:
            rows[parts[0]] = [int(v) for v in parts[1:]]
    out = [
        "package app.tilescreen.core;",
        "",
        "/** Generated by test/wake_tables.py from the C microfrontend: see MicroFrontend. Each char is one int16. */",
        "final class MicroTables {",
        "    private MicroTables() {}",
        "",
    ]
    for name in ORDER:
        values = rows[name]
        text = list(char(v & 0xFFFF) for v in values)
        chunks = ["".join(text[i:i + 16]) for i in range(0, len(text), 16)]
        out.append("    static final String %s =" % name.upper())
        out.append("\n".join('        "%s"%s' % (c, " +" if i + 1 < len(chunks) else ";") for i, c in enumerate(chunks)))
    out += [
        "",
        "    static short[] get(String table) {",
        "        short[] v = new short[table.length()];",
        "        for (int i = 0; i < v.length; i++) v[i] = (short) table.charAt(i);",
        "        return v;",
        "    }",
        "}",
        "",
    ]
    open("src/app/tilescreen/core/MicroTables.java", "w").write("\n".join(out))


if __name__ == "__main__":
    main(sys.argv[1])
